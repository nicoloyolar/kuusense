import 'dart:convert';
import 'dart:io';

/// Generates platform files from `shared/design/tokens.json`:
///   - shared/kuusense_ui/lib/src/generated/tokens.g.dart  (Flutter apps)
///   - shared/design/tokens.css                             (landing page / any web)
///
/// Run from the repo root: `make tokens`.
/// Token paths are flattened: color.brand.primary → KuuColor.brandPrimary /
/// --kuu-color-brand-primary. Keys starting with `$` are ignored.
void main() {
  final root = Directory.current.path;
  final tokens = jsonDecode(File('$root/shared/design/tokens.json').readAsStringSync())
      as Map<String, dynamic>;

  final dart = StringBuffer()
    ..writeln('// GENERATED by tools/design_tokens from shared/design/tokens.json.')
    ..writeln('// Do not edit by hand: change tokens.json and run `make tokens`.')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln();
  final css = StringBuffer()
    ..writeln('/* GENERATED by tools/design_tokens from shared/design/tokens.json.')
    ..writeln('   Do not edit by hand: change tokens.json and run `make tokens`. */')
    ..writeln(':root {');

  for (final group in tokens.entries.where((e) => !e.key.startsWith(r'$'))) {
    final leaves = <String, Object>{};
    _flatten(group.value, [], leaves);
    final className = 'Kuu${_pascal(group.key)}';
    dart.writeln('abstract final class $className {');
    for (final leaf in leaves.entries) {
      final name = _camel(leaf.key.split('.'));
      final cssName = '--kuu-${group.key}-${leaf.key.split('.').map(_kebab).join('-')}';
      final v = leaf.value;
      if (group.key == 'color') {
        dart.writeln('  static const $name = Color(${_argb(v as String)});');
        css.writeln('  $cssName: $v;');
      } else if (v is num) {
        dart.writeln('  static const double $name = ${v.toDouble()};');
        css.writeln('  $cssName: ${v}px;');
      } else {
        // Empty font family = platform default.
        dart.writeln("  static const String? $name = ${v == '' ? 'null' : "'$v'"};");
        css.writeln("  $cssName: ${v == '' ? 'system-ui, sans-serif' : "'$v', system-ui, sans-serif"};");
      }
    }
    dart
      ..writeln('}')
      ..writeln();
  }
  css.writeln('}');

  File('$root/shared/kuusense_ui/lib/src/generated/tokens.g.dart').writeAsStringSync(dart.toString());
  File('$root/shared/design/tokens.css').writeAsStringSync(css.toString());
  stdout.writeln('Tokens generados: tokens.g.dart y tokens.css');
}

void _flatten(Object? node, List<String> path, Map<String, Object> out) {
  if (node is Map<String, dynamic>) {
    for (final e in node.entries) {
      if (!e.key.startsWith(r'$')) _flatten(e.value, [...path, e.key], out);
    }
  } else if (node != null) {
    out[path.join('.')] = node;
  }
}

String _argb(String hex) {
  final h = hex.replaceFirst('#', '').toUpperCase();
  return '0x${h.length == 6 ? 'FF$h' : h}';
}

String _pascal(String s) => s[0].toUpperCase() + s.substring(1);
String _camel(List<String> parts) =>
    parts.first + parts.skip(1).map(_pascal).join();
String _kebab(String s) =>
    s.replaceAllMapped(RegExp('[A-Z]'), (m) => '-${m[0]!.toLowerCase()}');
